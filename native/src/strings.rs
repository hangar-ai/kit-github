/// The strings in the language of `locale`: French for `fr`, `fr-CA`…,
/// English for anything else (`pickLang` of logic.js).
pub fn strings(locale: &str) -> Strings {
    Strings::new(pick_lang(locale)).add("en", EN).add("fr", FR)
}

/// `fr` or `en`, as `logic.pickLang` chose.
pub fn pick_lang(locale: &str) -> &'static str {
    if locale.to_lowercase().starts_with("fr") {
        "fr"
    } else {
        "en"
    }
}
